"""Generate pokerbots/bots/preflop_table.py: equity of each 3-card starting
hand class vs one random 3-card hand, simulated through the flop discard.

Each player keeps the 2 cards with the best value on the flop (ties: higher
ranks), both discards are dead, then turn + river and showdown.

    python scripts/build_preflop_table.py --rollouts 16000
"""

import argparse
import os
import sys
import time
from itertools import combinations

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np  # noqa: E402

from pokerbots.core import rules  # noqa: E402
from pokerbots.core.evaluator import hand_value_batch  # noqa: E402
from pokerbots.bots.common import hand_class  # noqa: E402

FLOP = rules.STREETS[0][1]


def _keep(hole, flop):
    """Cheap discard policy, vectorised: hole (n,3) -> kept (n,2)."""
    n = len(hole)
    opts = [hole[:, [i for i in range(3) if i != j]] for j in range(3)]
    score = np.stack([hand_value_batch(o, flop) * 64 + (o // rules.NUM_SUITS).sum(axis=1)
                      for o in opts], axis=1)
    return np.stack(opts, axis=1)[np.arange(n), score.argmax(axis=1)]


def class_equity(hole, n, rng):
    deck = np.setdiff1d(np.arange(rules.DECK_SIZE), hole)
    keys = rng.random((n, len(deck)))
    d = deck[np.argpartition(keys, 10, axis=1)[:, :11]]
    flop, opp, rest = d[:, :FLOP], d[:, FLOP:FLOP + 3], d[:, FLOP + 3:]
    hero = np.broadcast_to(np.asarray(hole, dtype=np.int64), (n, 3))
    board = np.concatenate([flop, rest], axis=1)
    hv = hand_value_batch(_keep(hero, flop), board)
    ov = hand_value_batch(_keep(opp, flop), board)
    return ((hv > ov).sum() + 0.5 * (hv == ov).sum()) / n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rollouts", type=int, default=16000)
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()
    if rules.HOLE_CARDS != 3 or rules.KEEP_CARDS != 2:
        sys.exit("preflop table only defined for 3 hole cards, keep 2")
    rng = np.random.default_rng(args.seed)
    reps = {}
    for h in combinations(range(rules.DECK_SIZE), 3):
        reps.setdefault(hand_class(h), list(h))
    t = time.time()
    table = {cls: round(float(class_equity(hole, args.rollouts, rng)), 4)
             for cls, hole in sorted(reps.items())}
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "pokerbots", "bots", "preflop_table.py")
    with open(out, "w") as f:
        f.write('"""Generated by scripts/build_preflop_table.py (%d rollouts/class, seed %d).'
                '  Equity vs a random hand through the flop discard."""\n\n'
                % (args.rollouts, args.seed))
        f.write("RANKS = %r\nHOLE_CARDS = %d\nPREFLOP_EQUITY = {\n" % (rules.RANKS, rules.HOLE_CARDS))
        for cls in sorted(table, key=lambda c: -table[c]):
            f.write("    %r: %r,\n" % (cls, table[cls]))
        f.write("}\n")
    print("wrote %d classes to %s in %.1fs" % (len(table), out, time.time() - t))


if __name__ == "__main__":
    main()
